"""The sample files under Import knowledge (frontend/public/guides/templates) import cleanly.

They are what a customer copies, so they must survive the real NON-AI import path: every format
extracts, every topic is in the text, and no piece is cut through the middle of a line. They are
generated by backend/scripts/build_kb_samples.py; rebuild them there rather than editing by hand.
"""
import pathlib

import pytest

from app.services import kb_ingest

DIR = pathlib.Path(__file__).resolve().parents[2] / "frontend" / "public" / "guides" / "templates"
pytestmark = pytest.mark.skipif(not DIR.is_dir(), reason="frontend/public is not mounted")

FIRST = {"en": "Support hours", "ka": "მხარდაჭერის საათები"}
LAST = {"en": "Public holidays", "ka": "უქმე დღეები"}
FORMATS = ("pdf", "docx", "xlsx", "txt", "md")


def _pieces(path: pathlib.Path) -> tuple[str, list[str]]:
    data = path.read_bytes()
    if path.suffix == ".csv":
        pieces = [c for c, _ in kb_ingest.csv_to_chunks(data)]
        return "\n\n".join(pieces), pieces
    text = kb_ingest.extract_text(path.name, "", data)
    return text, kb_ingest.chunk_text(text)


@pytest.mark.parametrize("lang", ["en", "ka"])
@pytest.mark.parametrize("fmt", FORMATS)
def test_every_format_has_a_sample_that_imports_whole(lang, fmt):
    path = DIR / f"kb-template-{lang}.{fmt}"
    assert path.is_file(), f"missing sample {path.name}"
    text, pieces = _pieces(path)
    assert "﻿" not in text and "\x00" not in text
    flat = " ".join(text.lower().split())        # PDF justifies with double spaces; TXT upper-cases
    assert FIRST[lang].lower() in flat and LAST[lang].lower() in flat
    assert all(len(p) <= kb_ingest.CHUNK_SIZE for p in pieces)
    # Nothing is cut through a line: every line of every piece is a whole line of the source.
    source_lines = {ln.strip() for ln in text.replace("\r", "").split("\n") if ln.strip()}
    for piece in pieces:
        for ln in piece.split("\n"):
            assert not ln.strip() or ln.strip() in source_lines, ln[:60]
    assert len(pieces) >= 2           # long enough to show where the cuts fall


@pytest.mark.parametrize("lang", ["en", "ka"])
def test_csv_samples_are_one_entry_per_row(lang):
    qa = _pieces(DIR / f"kb-template-{lang}.csv")[1]
    assert len(qa) == 8 and all(": " in p for p in qa)
    table = _pieces(DIR / f"kb-template-{lang}-table.csv")[1]
    assert len(table) == 3 and all(p.count("\n") == 3 for p in table)     # four columns each
