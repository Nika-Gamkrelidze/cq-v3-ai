/* Transcription settings (tr.*) — the parameters sent to speech-to-text.

   Its own prefix rather than `stt.` (features/analysis.ts owns that one, for the transcribe
   PANEL) because these strings are a settings vocabulary rendered on three different surfaces:
   the operator console sets the deployment default, a workspace overrides it, and the person
   uploading one recording overrides that. Same words in all three places, or the inheritance
   is impossible to reason about. */

