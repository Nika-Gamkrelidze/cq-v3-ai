/* Shared chrome: the strings that belong to no single page.
   =========================================================
   Navigation, sign-in, session and error copy, and the small vocabularies the forms and
   tables of every page reuse (th., btn., f., tab., …). A page module must not redefine any
   of these — `scripts/check_i18n.py` fails the build if two migrated modules claim one key,
   which is the whole reason the dictionary is split by owner rather than by page.

   Everything except nav. is copied verbatim from brand.js, which still serves the pages that
   have not moved. The copy is deliberate: the legacy page needs its key until the day it is
   deleted. The checker reports every such pair as shared between the stacks, and that count
   is meant to fall to zero as the last .html files go. */

